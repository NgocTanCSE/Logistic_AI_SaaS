/** Tạo các lượt quét trong một phiên theo `totalMatched`/`totalMismatched` của seed. */
const createSessionScans = (session: PackSession): ScanLog[] => {
  const logs: ScanLog[] = [];
  const start = new Date(session.startedAt).getTime();
  const end = new Date(session.closedAt ?? session.startedAt).getTime();
  const qty = Math.max(1, session.totalPacked);
  for (let i = 0; i < qty; i++) {
    const order = orders[i % orders.length];
    const isMismatch = i >= session.totalMatched;
    logs.push({
      packCode: order.packCode,
      trackingCode: order.trackingCode,
      sku: order.expectedSku,
      expectedSku: order.expectedSku,
      result: isMismatch ? 'MISMATCH' : 'MATCH',
      confidence: isMismatch ? 62 + (i % 30) : 94 + (i % 6),
      stationId: session.stationId,
      staffId: session.staffId,
      note: isMismatch ? 'Quét thấy SKU-0009 nằm trong đơn, sản phẩm hỏng' : undefined,
      scannedAt: new Date(start + Math.round(((end - start) * i) / qty)).toISOString(),
    });
  }
  return logs;
};

